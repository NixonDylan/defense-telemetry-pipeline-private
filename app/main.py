# Place this structural middleware handler directly inside app/main.py
from fastapi import Request, status
from fastapi.responses import JSONResponse
from fastapi.exceptions import RequestValidationError
from app.database import db_manager
import json

@api_gateway.exception_handler(RequestValidationError)
async def pydantic_schema_exception_handler(request: Request, exc: RequestValidationError):
    """
    DevSecOps Middleware: Intercepts unhandled type/schema validations,
    extracts the malformed payload, and commits it into your immutable database ledger.
    """
    # 1. Capture the raw input payload data bytes that crashed the checker
    try:
        raw_body_bytes = await request.body()
        payload_captured = raw_body_bytes.decode("utf-8")
    except Exception:
        payload_captured = "Unreadable request body stream format"

    # 2. Extract the structured error trace generated by Pydantic v2
    error_summary = f"PYDANTIC_SCHEMA_VIOLATION: {str(exc.errors())}"

    # 3. Stream the bad packet directly into your permanent PostgreSQL ledger tables
    if db_manager.pool:
        query = """
            INSERT INTO telemetry_dlq (raw_payload, rejection_reason)
            VALUES ($1, $2);
        """
        try:
            async with db_manager.pool.acquire() as connection:
                await connection.execute(query, payload_captured, error_summary)
        except Exception as db_err:
            # Fallback output fallback tracing if connection pool experiences extreme stress
            print(f"Fallback critical log trace: {str(db_err)}")

    # 4. Standard secure API dropout response block
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content={
            "status": "REJECTED_METADATA_VIOLATION",
            "detail": exc.errors(),
            "note": "Payload structurally dropped at boundary line; error registry committed to ledger."
        }
    )
